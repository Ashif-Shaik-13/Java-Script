// 1. var, let and const

var name = "Ashif";
let age = 20;
const college = "Easwari College";

console.log(name);
console.log(age);
console.log(college);


// 2. Data types

let string = "Hello";
let number = 20;
let boolean = true;
let nullValue = null;
let undefinedValue;

console.log(string);
console.log(number);
console.log(boolean);
console.log(nullValue);
console.log(undefinedValue);


// 3. Operators

let a = 10;
let b = 5;

console.log(a + b);
console.log(a - b);
console.log(a * b);
console.log(a / b);
console.log(a % b);

console.log(a == b);
console.log(a === b);

console.log(a > 5 && b < 10);
console.log(a > 20 || b < 10);
